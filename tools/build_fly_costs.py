#!/usr/bin/env python3
"""Build manifest/part-fly-costs.tsv — the per-unit ("what it costs to FLY") price of every curated part.

WHY THIS EXISTS
AXE has two part prices and only ever authored one. `entryCost` (what you pay once, in R&D, to unlock a
part) is generated by build_tree.py into AxePartCost.cfg and is calibrated. The per-unit `cost` — what
the VAB charges every time you put the part on a rocket, i.e. the launch bill — was never authored at
all. RP-1's lived in `Tree/TREE-Parts.cfg`, which AXE replaced wholesale for its tree placement and
module tagging, taking the pricing half with it (docs/ECONOMY.md §14).

The consequence was not "launches are cheap" — it was that every NAMED part fell back to whatever its
own mod happened to ship, unnormalised across three orders of magnitude. Measured against RP-1:
a launch clamp cost 150 where RP-1 charged 1 (150x), while an RD-100 engine cost 1 where RP-1 charged
320 (0.003x). You paid more for the clamp than the engine.

WHAT THIS DOES
Recovers RP-1's own hand-tuned per-unit prices and writes them to a manifest that build_tree.py reads,
so the build does not depend on the RP-1 clone being present. Two sources, in priority order:

  1. `rp1`  — RP-1's `%cost` for the part. 1,478 of AXE's curated parts have one. This is a RESTORE,
              not an invention: RP-1 normalised these by hand and they are the shape we want back.
  2. `catmedian` — for AXE-curated parts RP-1 never priced, `mass x median(funds/tonne)` of RP-1's own
              parts in the same category. Derived from RP-1's pricing rather than guessed.

PROCEDURAL PARTS ARE DELIBERATELY OMITTED (source `proccosts`). Their per-unit cost does not come from
the PART's `cost` field at all — it is computed by the part's own modules from its dimensions
(`ProceduralPart.costPerkL`, RealFuels `TANK_DEFINITION.baseCost = k * volume`), which `seed/ProcCosts.cfg`
already configures with RP-1's numbers. AXE inherited that half intact. Writing a static `%cost` onto
them would price the same hardware twice. **The authority on which parts are static-priced is RP-1's own
TREE-Parts.cfg** — if RP-1 gave a part a static price we restore it; if it did not, and the part carries
a procedural cost module, we leave it to ProcCosts.

The `launch_cost_scalar` knob is NOT applied here — this manifest is the un-scaled baseline, so the
knob stays a single number in tree/nodes.yaml meta and re-tuning never requires regenerating this file.

Usage:  python tools/build_fly_costs.py         (needs the RP-1 clone as a sibling of the repo)
"""
import csv
import os
import re
import statistics
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "tools"))
from build_tree import costcat  # noqa: E402  SSOT for the cost-category taxonomy
RP1 = os.path.join(os.path.dirname(REPO), "RP-1", "GameData", "RP-1", "Tree", "TREE-Parts.cfg")
CAPS = os.path.join(REPO, "manifest", "part-capabilities.tsv")
OUT = os.path.join(REPO, "manifest", "part-fly-costs.tsv")

# A part whose per-unit cost is computed by its own modules from dimensions. Only consulted for parts
# RP-1 did NOT price — RP-1's own judgement wins wherever it expressed one.
PROC_MODULES = ("ProceduralPart", "ProceduralFairingBase", "ProceduralFairingSide")
PROC_NAMES = re.compile(r"procedural|B9Proc", re.I)


def rp1_costs():
    """part -> RP-1's per-unit %cost, parsed from TREE-Parts.cfg's @PART blocks."""
    if not os.path.isfile(RP1):
        sys.exit(f"RP-1 clone not found at {RP1}\n"
                 "This tool regenerates a checked-in manifest; it needs the RP-1 source clone.")
    txt = open(RP1, encoding="utf-8", errors="replace").read()
    out = {}
    for m in re.finditer(r"@PART\[([^\]]+)\][^\n]*\n(.*?)\n(?=@PART\[|\Z)", txt, re.S):
        c = re.search(r"^\s*[@%]cost = ([0-9.]+)", m.group(2), re.M)
        if c:
            out[m.group(1)] = float(c.group(1))
    return out


def is_procedural(row):
    return PROC_NAMES.search(row["name"]) or any(m in (row.get("modules") or "") for m in PROC_MODULES)


def main():
    rp1 = rp1_costs()
    rows = list(csv.DictReader(open(CAPS, encoding="utf-8", errors="replace"), delimiter="\t"))

    # RP-1's implicit funds/tonne per COST-category, from the parts it priced that we also carry.
    #
    # Keyed on build_tree's costcat(), not the raw KSP `category` field. That is not cosmetic: the
    # ModularLaunchPads structures report category `none`, so keying on the raw field priced a 2,500 t
    # launch base at 4,009,358 off an unrelated median. costcat classifies them `ground` — scenery you
    # bolt to the pad — which is also how AxePartCost.cfg weights them (0.2, the cheapest class).
    # Using the same taxonomy for both prices means "what you pay to unlock" and "what you pay to fly"
    # can never disagree about what kind of thing a part is.
    #
    # Median, not mean: the spreads run 4x-42x within a category, so this is a central tendency for
    # filling gaps, never a claim that RP-1's pricing is a formula.
    cats = {r["name"]: costcat(r.get("category", ""), r.get("disc", ""), r.get("modules", ""), r.get("mod", ""))
            for r in rows}
    per_t = {}
    for r in rows:
        c = rp1.get(r["name"])
        try:
            mass = float(r["mass"])
        except (TypeError, ValueError):
            continue
        if c and c > 1 and mass > 0:
            per_t.setdefault(cats[r["name"]], []).append(c / mass)
    med = {k: statistics.median(v) for k, v in per_t.items() if len(v) >= 3}
    fallback = statistics.median(med.values()) if med else 1000.0

    out, counts = [], {"rp1": 0, "catmedian": 0, "proccosts": 0, "nomass": 0}
    for r in sorted(rows, key=lambda x: x["name"]):
        name = r["name"]
        try:
            mass = float(r["mass"])
        except (TypeError, ValueError):
            mass = 0.0
        cc = cats[name]
        if name in rp1:
            # RP-1's own judgement wins wherever it expressed one -- INCLUDING its zeroes. It prices
            # every procedural part at 0 precisely because that part's modules compute the cost from
            # dimensions; restoring the 0 is correct, not a gap.
            out.append((name, round(rp1[name], 2), "rp1", cc, mass)); counts["rp1"] += 1
        elif is_procedural(r):
            counts["proccosts"] += 1                      # ProcCosts.cfg owns it; omit from the file
        elif mass > 0:
            cost = round(mass * med.get(cc, fallback), 2)
            out.append((name, cost, "catmedian", cc, mass)); counts["catmedian"] += 1
        else:
            counts["nomass"] += 1                         # nothing to scale; leave at its mod default

    with open(OUT, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, delimiter="\t", lineterminator="\n")
        w.writerow(["part", "cost", "source", "category", "mass"])
        w.writerows(out)

    total = sum(c for _, c, _, _, _ in out)
    print(f"fly costs: {len(out)} parts priced ({total:,.0f} funds if you flew one of each) -> {os.path.relpath(OUT, REPO)}")
    print(f"  from RP-1's own numbers   : {counts['rp1']}")
    print(f"  category-median fallback  : {counts['catmedian']}")
    print(f"  left to ProcCosts.cfg     : {counts['proccosts']}  (dimension-priced; a static cost would double-charge)")
    print(f"  no mass, left at mod value: {counts['nomass']}")
    print("  RP-1 funds/tonne by category: " +
          ", ".join(f"{k}={v:,.0f}" for k, v in sorted(med.items(), key=lambda x: -x[1])))


if __name__ == "__main__":
    main()
