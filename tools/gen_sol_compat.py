"""Generate RP-AXE's Sol compatibility layer: GameData/RP-AXE/design/Sol/.

Sol (RSS-Reborn) replaces RealSolarSystem. It satisfies CKAN's `RealSolarSystem` dependency, but
in ModuleManager it registers the pass `SolSystem`, never `RealSolarSystem`, and it defines its
bodies at :FOR[SolSystem] -- a pass that sorts AFTER RP-0 and RP-AXE. So every AXE patch on a body
(:FOR[RP-0], :AFTER[RP-0], :AFTER[RealSolarSystem]) runs before the body exists, or never, and does
nothing without a word in the log. Sol also ships its own copies of a few RSS-side configs, which
drift from what AXE is balanced on.

This tool writes two kinds of file, all gated on SolSystem (inert on RSS):
  * TWINS of AXE's own body patches -- the repo file verbatim, pass and home-body name rewritten:
      AxeSolBodyScience.cfg      seed/Science/BodyScienceParams.cfg + design/Science/EarthScienceRemoval.cfg
      AxeSolGasGiantEmissive.cfg design/AxeGasGiantEmissiveFix.cfg
  * SNAPSHOTS of the final values on RSS, read from the RSS dev instance's merged cache, so parity
    holds by construction:
      AxeSolScanners.cfg   SCANsat altitudes + EC (Sol triples every scanner's altitudes)
      AxeSolStations.cfg   RealAntennas ground-station antennas (Sol's copy lacks the DSN Ka band)
      AxeSolResources.cfg  outer-planet resource maps (Sol ships them for Venus/Earth/Moon/Mars only)

    python tools/gen_sol_compat.py           # regenerate
    python tools/gen_sol_compat.py --check   # exit 1 if a file is stale (re-run after an RP-1 seed
                                             # sync or a dev-instance rebuild)
    python tools/gen_sol_compat.py --verify ../ksp_sol/GameData/ModuleManager.ConfigCache
                                             # booted Sol instance vs the RSS one, on everything above
                                             # plus radiation belts and the tracking-station ladder

Measured against Sol 0.9.5 (2026-10-23); docs/SOL.md has the full comparison.
"""
import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
AXE = REPO / "GameData" / "RP-AXE"
OUT = AXE / "design" / "Sol"
DEFAULT_CACHE = REPO.parent / "Instance" / "GameData" / "ModuleManager.ConfigCache"

# Bodies Sol 0.9.5 ships no PLANETARY_RESOURCE for (it copies RSS's Venus/Earth/Moon/Mars maps).
# Re-measure when Sol updates: adding a body Sol already covers would double its resources.
SOL_MISSING_RESOURCES = ["Jupiter", "Io", "Saturn", "Titan", "Uranus", "Neptune", "Pluto", "Charon"]

SCANNER_MODULES = ("SCANsat", "ModuleSCANresourceScanner")
SCANNER_KEYS = ("min_alt", "max_alt", "best_alt")


# ---------------------------------------------------------------- ConfigNode in / out

class Node:
    def __init__(self, name):
        self.name, self.values, self.nodes = name, [], []

    def get(self, key):
        return next((v for k, v in self.values if k == key), None)

    def child(self, name):
        return next((n for n in self.nodes if n.name == name), None)


def parse_cache(path):
    """ModuleManager.ConfigCache -> [(parentUrl, top-level Node)]. One assignment per line."""
    root, stack, pending = Node("root"), None, None
    stack = [root]
    for raw in Path(path).read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw.split("//", 1)[0].strip()
        for tok in (t.strip() for t in re.split(r"([{}])", line)):
            if not tok:
                continue
            if tok == "{":
                n = Node(pending or "")
                stack[-1].nodes.append(n)
                stack.append(n)
                pending = None
            elif tok == "}":
                pending = None
                if len(stack) > 1:
                    stack.pop()
            elif "=" in tok:
                k, v = tok.split("=", 1)
                stack[-1].values.append((k.strip(), v.strip()))
                pending = None
            else:
                pending = tok
    return [(uc.get("parentUrl"), n) for uc in root.nodes if uc.name == "UrlConfig" for n in uc.nodes]


def emit(node, depth, header=None):
    """Node -> cfg lines (tabs). `header` replaces the node's own name line (for patch syntax)."""
    pad = "\t" * depth
    out = [pad + (header or node.name), pad + "{"]
    out += [f"{pad}\t{k} = {v}" for k, v in node.values]
    for c in node.nodes:
        out += emit(c, depth + 1)
    out.append(pad + "}")
    return out


def has_pattern(value):
    """A value for MM's HAS[#key[...]]: every character outside [A-Za-z0-9-] becomes the ? wildcard."""
    return re.sub(r"[^A-Za-z0-9\-]", "?", value)


def banner(*lines):
    return ["// GENERATED by tools/gen_sol_compat.py — DO NOT EDIT BY HAND"] + [f"// {l}" if l else "//" for l in lines]


# ---------------------------------------------------------------- twins of AXE's own body patches

def twin(rel, rewrites):
    """The repo file from its first patch line on, with `rewrites` (old, new) each applied exactly once
    and the trailing comment dropped from every rewritten line (it described the RSS case)."""
    text = (AXE / rel).read_text(encoding="utf-8")
    lines = text.splitlines()
    start = next(i for i, l in enumerate(lines) if l.lstrip().startswith("@"))
    body = lines[start:]
    for old, new in rewrites:
        hits = [i for i, l in enumerate(body) if old in l]
        if len(hits) != 1:
            sys.exit(f"gen_sol_compat: expected exactly one '{old}' in {rel}, found {len(hits)} -- "
                     "the source changed shape; update the rewrite")
        i = hits[0]
        body[i] = body[i].replace(old, new).split("//", 1)[0].rstrip()
    return [f"// --- from {rel}"] + body


def unpatched_science(cache):
    """RSS's own ScienceValues for the bodies the seed does not patch (the Sun: RSS puts its 'high space'
    boundary at 15,000,000 km, Sol keeps stock's 1,000,000 km)."""
    seed = (AXE / "seed/Science/BodyScienceParams.cfg").read_text(encoding="utf-8")
    patched = {"Earth" if b == "Kerbin" else b for b in re.findall(r"@Body\[(\w+)\]", seed)}
    out = []
    for _, n in cache:
        if n.name != "Kopernicus":
            continue
        for b in n.nodes:
            name = b.get("cbNameLater") or b.get("name")
            sv = b.child("Properties").child("ScienceValues") if b.name == "Body" and b.child("Properties") else None
            if sv is None or name in patched or not sv.values:
                continue
            out += [f"\t@Body[{name}]", "\t{", "\t\t@Properties", "\t\t{", "\t\t\t%ScienceValues", "\t\t\t{"]
            out += [f"\t\t\t\t%{k} = {v}" for k, v in sv.values]
            out += ["\t\t\t}", "\t\t}", "\t}"]
    if not out:
        return []
    return ["// --- RSS's own values for the bodies the seed leaves alone (RSS dev instance's merged cache)",
            "@Kopernicus:AFTER[SolSystem]", "{"] + out + ["}"]


def body_science(cache):
    return "\n".join(banner(
        "Sol twin of AXE's per-body science values. On Sol, seed/Science/BodyScienceParams.cfg",
        "(:FOR[RP-0], @Body[Kerbin]) and design/Science/EarthScienceRemoval.cfg (:AFTER[RP-0]) run",
        "before Sol creates its bodies at :FOR[SolSystem], and Sol names the home body Earth, not",
        "Kerbin. Without this file Sol's own multipliers stand (3-5x lower on most bodies), the tree's",
        "science budget no longer adds up, and Earth's sub-40 km science is farmable again.",
        "Same content, pass rewritten to :AFTER[SolSystem]; the removal follows the params in file order.",
        "Last, RSS's own values for bodies the seed leaves alone (the Sun), from the RSS dev instance.",
        "Bodies only Sol has (Pallas, Eros, Arrokoth, ...) keep Sol's values.",
    ) + [""] + twin("seed/Science/BodyScienceParams.cfg", [
        ("@Kopernicus:FOR[RP-0]", "@Kopernicus:AFTER[SolSystem]"),
        ("@Body[Kerbin]", "@Body[Earth]"),
    ]) + [""] + twin("design/Science/EarthScienceRemoval.cfg", [
        ("@Kopernicus:AFTER[RP-0]", "@Kopernicus:AFTER[SolSystem]"),
        ("@Body[Kerbin]", "@Body[Earth]"),
    ]) + [""] + unpatched_science(cache)) + "\n"


def gas_giant_emissive():
    return "\n".join(banner(
        "Sol twin of design/AxeGasGiantEmissiveFix.cfg, which runs :AFTER[RealSolarSystem] and so never",
        "on Sol. Sol 0.9.5 ships the same 1000 atm datum curves as RSS (Saturn key 0 = 1005.6 K,",
        "Uranus 731.3 K, Neptune 717.7 K -- checked against both installs), so the fix applies as is.",
    ) + [""] + twin("design/AxeGasGiantEmissiveFix.cfg", [
        ("@Kopernicus:AFTER[RealSolarSystem]", "@Kopernicus:AFTER[SolSystem]"),
    ])) + "\n"


# ---------------------------------------------------------------- snapshots of the RSS side

def scanners(cache):
    out = banner(
        "SCANsat altitudes and EC rates as they end up on RSS, re-asserted on Sol.",
        "Sol-Configs/Patches/Sol-SCANsat.cfg multiplies min/max/best altitude of EVERY scanner by 3 at",
        ":FOR[SolSystem], after RealismOverhaul has tuned them (RO-HIRES best 300 km -> 900 km), and",
        "RSS's own per-sensorType catch-all is absent. Values: the RSS dev instance's merged cache,",
        "after design/Parts/AxeUpstreamPartFixes.cfg. :LAST[RP-AXE], after Sol and AXE's own fixes.",
    )
    count = 0
    for _, part in sorted(((u, n) for u, n in cache if n.name == "PART"), key=lambda t: t[1].get("name") or ""):
        stanzas, seen = [], {}
        for m in part.nodes:
            mname = m.get("name")
            if m.name != "MODULE" or mname not in SCANNER_MODULES:
                continue
            idx = seen.get(mname, 0)
            seen[mname] = idx + 1
            sel = f"@MODULE[{mname}]" + (f",{idx}" if idx else "")
            inner = [f"\t\t@{k} = {m.get(k)}" for k in SCANNER_KEYS if m.get(k) is not None]
            ec = next((r for r in m.nodes if r.name == "RESOURCE" and r.get("name") == "ElectricCharge"), None)
            if ec is not None and ec.get("rate") is not None:
                inner += ["\t\t@RESOURCE[ElectricCharge]", "\t\t{", f"\t\t\t@rate = {ec.get('rate')}", "\t\t}"]
            if inner:
                stanzas += [f"\t{sel}", "\t{"] + inner + ["\t}"]
        if stanzas:
            out += ["", f"@PART[{part.get('name')}]:NEEDS[SolSystem]:LAST[RP-AXE]", "{"] + stanzas + ["}"]
            count += 1
    if count == 0:
        sys.exit("gen_sol_compat: no SCANsat parts in the cache -- is it an RP-AXE instance?")
    return "\n".join(out) + "\n"


def stations(cache):
    earth = None
    for url, n in cache:
        if n.name != "Kopernicus":
            continue
        for b in n.nodes:
            if b.name == "Body" and b.get("name") == "Kerbin" and b.child("PQS") is not None:
                earth = b
    if earth is None:
        sys.exit("gen_sol_compat: no RSS home body (Body[Kerbin]) in the cache -- not an RSS instance?")
    mods = earth.child("PQS").child("Mods")
    out = banner(
        "RealAntennas ground-station antennas as they are on RSS, re-asserted on Sol.",
        "Sol ships its own copy of RA's station table (Sol-Configs/Patches/CommNet/RealAntennas-RO.cfg,",
        "@Body[Earth]) because RA's own targets @Body[Kerbin]. Against RA 2.12 that copy has no TechLevel 10",
        "Ka-band upgrade at the three DSN sites and older encoders elsewhere, so the top of AXE's",
        "tracking-station ladder buys less deep-space link on Sol. Only the Antenna nodes are replaced;",
        "Sol's station placement, model and LOD stay. Values: the RSS dev instance's merged cache.",
        "",
        "@Kopernicus:NEEDS[SolSystem]:LAST[RP-AXE] -- after Sol's copy (:AFTER[zRealAntennas]).",
    ) + ["", "@Kopernicus:NEEDS[SolSystem]:LAST[RP-AXE]", "{", "\t@Body[Earth]", "\t{", "\t\t@PQS", "\t\t{",
         "\t\t\t@Mods", "\t\t\t{"]
    count = 0
    for city in mods.nodes:
        antennas = [a for a in city.nodes if a.name == "Antenna"]
        name = city.get("objectName")
        if city.name != "City2" or not antennas or not name:
            continue
        out += [f"\t\t\t\t// {name}", f"\t\t\t\t@City2:HAS[#objectName[{has_pattern(name)}]]", "\t\t\t\t{",
                "\t\t\t\t\t!Antenna,* {}"]
        for a in antennas:
            out += emit(a, 5)
        out.append("\t\t\t\t}")
        count += 1
    if count == 0:
        sys.exit("gen_sol_compat: no RealAntennas stations on the RSS home body")
    out += ["\t\t\t}", "\t\t}", "\t}", "}"]
    return "\n".join(out) + "\n"


def resources(cache):
    out = banner(
        "Outer-planet resource maps from RealSolarSystem, for the bodies Sol 0.9.5 ships none for:",
        ", ".join(SOL_MISSING_RESOURCES) + ".",
        "Without them Kerbalism harvesters find nothing in those atmospheres and oceans on Sol.",
        "",
        "Data: RealSolarSystem/ResourceConfigs (KSP-RO, CC-BY-NC-SA), copied from the RSS dev",
        "instance's merged cache.",
    )
    count = 0
    for url, n in cache:
        if n.name == "PLANETARY_RESOURCE" and (url or "").startswith("RealSolarSystem/") \
                and n.get("PlanetName") in SOL_MISSING_RESOURCES:
            out += [""] + emit(n, 0, header="PLANETARY_RESOURCE:NEEDS[SolSystem]")
            count += 1
    if count == 0:
        sys.exit("gen_sol_compat: no RSS outer-planet PLANETARY_RESOURCE nodes in the cache")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- verify a booted Sol instance

def bodies(cache):
    """{runtime body name: Body node}. RSS keeps its home body as Body[Kerbin] + cbNameLater = Earth."""
    out = {}
    for _, n in cache:
        if n.name == "Kopernicus":
            for b in n.nodes:
                if b.name == "Body":
                    out[b.get("cbNameLater") or b.get("name")] = b
    return out


def flat(node):
    """Node -> sorted 'path=value' lines, for comparing whole subtrees."""
    out = []

    def walk(n, path):
        out.extend(f"{path}{k}={v}" for k, v in n.values)
        for i, c in enumerate(n.nodes):
            walk(c, f"{path}{c.name}[{i}]/")
    walk(node, "")
    return out


def verify(rss, sol):
    """Every fact the Sol layer is meant to restore, RSS cache vs Sol cache. -> number of mismatches."""
    bad = 0

    def report(title, diffs, total):
        nonlocal bad
        bad += len(diffs)
        print(f"{'OK  ' if not diffs else 'DIFF'} {title}: {total - len(diffs)}/{total} match")
        for d in diffs[:12]:
            print("       ", d)
        if len(diffs) > 12:
            print(f"        ... {len(diffs) - 12} more")

    rb, sb = bodies(rss), bodies(sol)
    common = sorted(set(rb) & set(sb))
    diffs = []
    for name in common:
        r = rb[name].child("Properties").child("ScienceValues") if rb[name].child("Properties") else None
        s = sb[name].child("Properties").child("ScienceValues") if sb[name].child("Properties") else None
        rv, sv = dict(r.values) if r else {}, dict(s.values) if s else {}
        keys = []
        # only the keys RSS defines: a key RSS leaves out falls back to the Kopernicus template (stock),
        # which is what Sol writes out explicitly (the Sun: x11 low space, x2 high space, x4 recovery)
        for k in sorted(rv):
            try:
                same = float(rv.get(k)) == float(sv.get(k))
            except (TypeError, ValueError):
                same = rv.get(k) == sv.get(k)
            if not same:
                keys.append(f"{k} {rv.get(k)}/{sv.get(k)}")
        if keys:
            diffs.append(f"{name} (RSS/Sol): " + ", ".join(keys))
    report(f"body ScienceValues (Sol-only bodies keep Sol's: {', '.join(sorted(set(sb) - set(rb)))})",
           diffs, len(common))

    diffs = []
    for name in ("Jupiter", "Saturn", "Uranus", "Neptune"):
        keys = [b.child("Atmosphere").child("temperatureCurve").values[:2] for b in (rb[name], sb[name])]
        if keys[0] != keys[1]:
            diffs.append(f"{name} temperatureCurve: RSS {keys[0]} / Sol {keys[1]}")
    report("gas-giant emissive datum", diffs, 4)

    def scanner_map(cache):
        out = {}
        for _, p in cache:
            if p.name == "PART":
                for i, m in enumerate(p.nodes):
                    if m.name == "MODULE" and m.get("name") in SCANNER_MODULES:
                        out[f"{p.get('name')}#{i}"] = flat(m)
        return out
    rs, ss = scanner_map(rss), scanner_map(sol)
    diffs = [k for k in sorted(rs) if k in ss and rs[k] != ss[k]]
    report("SCANsat modules", diffs, len(set(rs) & set(ss)))

    def station_map(b):
        mods = b.child("PQS").child("Mods")
        return {c.get("objectName"): [l for a in c.nodes if a.name == "Antenna" for l in flat(a)]
                for c in mods.nodes if c.name == "City2" and c.get("objectName")}
    rst, sst = station_map(rb["Earth"]), station_map(sb["Earth"])
    diffs = [k for k in sorted(rst) if k in sst and rst[k] != sst[k]]
    report(f"ground-station antennas (RSS {len(rst)} / Sol {len(sst)} stations)", diffs, len(set(rst) & set(sst)))

    def res_count(cache):
        out = {}
        for _, n in cache:
            if n.name == "PLANETARY_RESOURCE":
                out[n.get("PlanetName")] = out.get(n.get("PlanetName"), 0) + 1
        return out
    rr, sr = res_count(rss), res_count(sol)
    diffs = [f"{b}: RSS {rr.get(b, 0)} / Sol {sr.get(b, 0)}" for b in common if rr.get(b, 0) != sr.get(b, 0)]
    report("PLANETARY_RESOURCE per body", diffs, len(common))

    def radiation(cache):
        out = {}
        for _, n in cache:
            if n.name in ("RadiationBody", "RadiationModel"):
                # case-folded: Sol names its belt model "Saturn" where RSS has "saturn", consistently
                # on both sides of each install
                out.setdefault(f"{n.name}[{n.get('name').lower()}]", []).append(sorted(l.lower() for l in flat(n)))
        return out
    rad_r, rad_s = radiation(rss), radiation(sol)
    diffs = []
    for k in sorted(set(rad_r) | set(rad_s)):
        if rad_r.get(k) != rad_s.get(k):
            a, b = rad_r.get(k) or [[]], rad_s.get(k) or [[]]
            delta = sorted(set(a[-1]) ^ set(b[-1]))
            diffs.append(f"{k}: " + ("; ".join(delta[:6]) if delta else f"{len(a)} vs {len(b)} node(s)"))
    report("Kerbalism radiation models + bodies", diffs, len(set(rad_r) | set(rad_s)))

    def tracking(cache):
        return [flat(n.child("TRACKING")) for _, n in cache if n.name == "CUSTOMBARNKIT"]
    report("tracking-station ladder (CUSTOMBARNKIT TRACKING)", [] if tracking(rss) == tracking(sol) else ["differs"], 1)
    return bad


# ---------------------------------------------------------------- main

def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--rss-cache", default=str(DEFAULT_CACHE),
                    help="merged ModuleManager.ConfigCache of an RSS RP-AXE instance (default: ../Instance)")
    ap.add_argument("--check", action="store_true", help="fail if any generated file is stale")
    ap.add_argument("--verify", metavar="SOL_CACHE",
                    help="compare a booted Sol instance's merged cache against the RSS one and exit")
    args = ap.parse_args()

    cache = parse_cache(args.rss_cache)
    if args.verify:
        bad = verify(cache, parse_cache(args.verify))
        sys.exit(f"{bad} mismatch(es)" if bad else 0)
    files = {
        "AxeSolBodyScience.cfg": body_science(cache),
        "AxeSolGasGiantEmissive.cfg": gas_giant_emissive(),
        "AxeSolScanners.cfg": scanners(cache),
        "AxeSolStations.cfg": stations(cache),
        "AxeSolResources.cfg": resources(cache),
    }
    stale = []
    for name, text in files.items():
        path = OUT / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(name)
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(REPO)}")
    if args.check:
        if stale:
            sys.exit("STALE: " + ", ".join(stale) + " -- run python tools/gen_sol_compat.py")
        print("design/Sol up to date")


if __name__ == "__main__":
    main()
