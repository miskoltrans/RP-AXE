#!/usr/bin/env python3
"""Extract the parts + upgrades RP-1 places at the 'first-orbit milestone' nodes, from the
rp1_expanded ConfigCache (RP-1 tree active), and cross-reference against our curated manifest."""
import os, collections

CC = r"C:\git\ksp_rp1_expanded\GameData\ModuleManager.ConfigCache"
REPO = r"C:\git\ksp\RP-AXE"
CURATED = os.path.join(REPO, "manifest", "curated-parts.tsv")
UPGRADES = os.path.join(REPO, "manifest", "upgrades-curated.tsv")
OUT_TSV = os.path.join(REPO, "manifest", "first-orbit-partlist.tsv")
OUT_MD  = os.path.join(REPO, "manifest", "first-orbit-partlist.md")

NODES = [  # ordered
 ("start","Start (RP-1)"),
 ("unlockParts","Starting Parts (RP-1)"),
 ("rocketryTesting","Post-War Rocketry Testing"),
 ("earlyRocketry","Early Rocketry"),
 ("basicRocketryRP0","Basic Rocketry"),
 ("orbitalRocketry1956","1956-1957 Orbital Rocketry"),
 ("earlySolids","Early Solid Rocket Engines"),
 ("basicSolids","Basic Solid Rocket Engines"),
 ("solids1956","1956-1957 Solid Rocket Engines"),
 ("postWarMaterialsScience","Post-War Materials Science"),
 ("earlyMaterialsScience","Early Materials Science"),
 ("materialsScienceSatellite","Satellite Era Materials Science"),
 ("electronicsSatellite","Satellite Era Electronics Research"),
 ("postWarAvionics","Early Tracking Systems"),
 ("avionicsPrototypes","Avionics Prototypes"),
 ("earlyAvionics","Early Avionics and Probes"),
 ("earlyScience","Early Science"),
 ("scienceSatellite","Satellite Era Science"),
 ("supersonicDev","Supersonic Plane Development"),
 ("supersonicFlightRP0","Supersonic Flight"),
 ("matureSupersonic","Mature Supersonic Flight"),
]
NSET = {k for k, _ in NODES}
TITLE = dict(NODES)
# We deliberately keep OUR start smaller than RP-1's (don't overwhelm the player): RP-1 start/unlockParts
# parts already in our startlist drop out; the rest are added to the list to be homed deeper in the tree.
OUR_START = {"proceduralNoseCone", "proceduralStructural", "RO-RFTank-Separate", "proceduralAvionics",
             "B9_Aero_Wing_Procedural_TypeA", "sensorBarometer", "sensorThermometer"}

def load_tsv(path):
    with open(path, encoding="utf-8") as f:
        header = f.readline().rstrip("\n").split("\t")
        rows = [l.rstrip("\n").split("\t") for l in f]
    return header, rows

ph, prows = load_tsv(CURATED)
pn = ph.index("name"); pt = ph.index("title")
curated_title = {r[pn]: r[pt] for r in prows if len(r) > pt}
# ModularLaunchPads = launch-pad/tower part bloat; excluded here, inserted separately later.
EXCLUDE_MODS = {"ModularLaunchPads"}
pm = ph.index("mod")
excluded = {r[pn] for r in prows if len(r) > pm and r[pm] in EXCLUDE_MODS}

uh, urows = load_tsv(UPGRADES)
print("upgrades-curated header:", uh)
un = uh.index("name") if "name" in uh else 0
ud = uh.index("disposition") if "disposition" in uh else None
curated_up = {}
for r in urows:
    if len(r) > un:
        curated_up[r[un]] = (r[ud] if ud is not None and len(r) > ud else "?")

# --- parse ConfigCache: brace-depth walk, capture PART/PARTUPGRADE name+title+TechRequired ---
part_nodes = collections.defaultdict(list)
up_nodes = collections.defaultdict(list)
titles = {}
stack, pending, cur = [], None, None
with open(CC, encoding="utf-8", errors="replace") as f:
    for line in f:
        s = line.strip()
        if s == "{":
            stack.append(pending)
            if pending in ("PART", "PARTUPGRADE") and cur is None:
                cur = {"type": pending, "name": None, "title": None, "tech": None, "depth": len(stack)}
            pending = None
        elif s == "}":
            if stack: stack.pop()
            if cur and len(stack) < cur["depth"]:
                if cur["tech"] in NSET and cur["name"]:
                    (part_nodes if cur["type"] == "PART" else up_nodes)[cur["tech"]].append(cur["name"])
                    if cur["title"]: titles[cur["name"]] = cur["title"]
                cur = None
        elif "=" in s and not s.startswith("//"):
            k, _, v = s.partition("="); k = k.strip(); v = v.strip()
            if cur and stack and stack[-1] in ("PART", "PARTUPGRADE"):
                if k == "name" and cur["name"] is None: cur["name"] = v
                elif k == "title" and cur["title"] is None: cur["title"] = v
                elif k.lower() == "techrequired": cur["tech"] = v
            pending = None
        elif s and not s.startswith("//"):
            pending = s

# --- emit ---
tot_p = tot_pc = tot_u = 0
md = ["# First-Orbit Milestone Partlist (extracted from RP-1 @ rp1_expanded)\n",
      "Parts + upgrades RP-1 places at the early nodes up to the first-orbit milestone, cross-referenced",
      "against our curated set. ✓=curated (in manifest), ✗=uncurated. Upgrade tag = our disposition.\n",
      "Source: `C:\\git\\ksp_rp1_expanded` ConfigCache. Generated by tools/extract_first_orbit_partlist.py.\n"]
tsv = ["node\tnode_title\tkind\tname\tcurated\ttitle"]
for nid, ntitle in NODES:
    parts = sorted(set(part_nodes.get(nid, [])))
    if nid in ("start", "unlockParts"):
        parts = [p for p in parts if p not in OUR_START]   # smaller start: drop what we already give at our start
    parts = [p for p in parts if p not in excluded]        # ModularLaunchPads inserted separately
    ups = sorted(set(up_nodes.get(nid, [])))
    if not parts and not ups: continue
    nc = sum(1 for p in parts if p in curated_title)
    md.append(f"\n## {ntitle}  `{nid}`  — {len(parts)} parts ({nc} curated), {len(ups)} upgrades")
    for p in parts:
        c = p in curated_title
        t = curated_title.get(p) or titles.get(p, "")
        md.append(f"- {'✓' if c else '✗'} `{p}`  {t}")
        tsv.append(f"{nid}\t{ntitle}\tpart\t{p}\t{'yes' if c else 'no'}\t{t}")
        tot_p += 1; tot_pc += c
    for u in ups:
        disp = curated_up.get(u)
        if disp is None:  # solarTL*/commsTL* = tech-level ladders to INCLUDE later (user note), not drop
            disp = "KEEP-techlevel-TODO" if u.startswith(("solarTL", "commsTL")) else "not-in-curated"
        md.append(f"  - ⬆ `{u}`  [{disp}]")
        tsv.append(f"{nid}\t{ntitle}\tupgrade\t{u}\t{disp}\t")
        tot_u += 1

with open(OUT_TSV, "w", encoding="utf-8") as f: f.write("\n".join(tsv) + "\n")
with open(OUT_MD, "w", encoding="utf-8") as f: f.write("\n".join(md) + "\n")
print(f"\nTOTAL: {tot_p} parts ({tot_pc} curated / {tot_p-tot_pc} uncurated), {tot_u} upgrades")
print("per-node parts (curated/total):")
for nid, ntitle in NODES:
    parts = sorted(set(part_nodes.get(nid, [])))
    if nid in ("start", "unlockParts"): parts = [p for p in parts if p not in OUR_START]
    parts = [p for p in parts if p not in excluded]
    if parts:
        nc = sum(1 for p in parts if p in curated_title)
        print(f"  {nc:>3}/{len(parts):<3}  {nid:<26} {ntitle}")
print(f"-> {OUT_TSV}\n-> {OUT_MD}")
